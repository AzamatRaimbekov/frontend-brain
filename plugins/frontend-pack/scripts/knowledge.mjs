#!/usr/bin/env node
// Knowledge base of the frontend brain: plugins/frontend-pack/knowledge/<area>/<slug>.md
// Usage:
//   node knowledge.mjs search <words...> [--stack next] [--area data]   top 8 entries by weighted stem match (works in any installed copy)
//   node knowledge.mjs index                                            rewrite knowledge/INDEX.md
//   node knowledge.mjs check                                            validate entries and INDEX.md, exit 1 on errors
import { readFileSync, readdirSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { join, dirname, basename, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

export const KNOWLEDGE = join(dirname(fileURLToPath(import.meta.url)), '..', 'knowledge');
export const AREAS = [
  'project-setup', 'architecture', 'data', 'ui', 'ux', 'forms', 'state', 'errors',
  'testing', 'performance', 'a11y', 'security', 'i18n', 'tooling', 'mobile',
];
export const TYPES = ['rule', 'recipe', 'decision', 'gotcha'];
export const STACKS = ['all', 'react', 'vite', 'next', 'expo'];
const STATUSES = ['active', 'deprecated'];
const REQUIRED_HEADINGS = ['## Решение', '## Почему'];
const MAX_LINES = 150;

// Minimal frontmatter parser: `key: value` and `key: [a, b]`.
function parse(text) {
  const match = text.match(/^---\n([\s\S]*?)\n---\n/);
  if (!match) return { meta: null, body: text };
  const meta = {};
  for (const line of match[1].split('\n')) {
    const kv = line.match(/^([a-z_]+):\s*(.*)$/);
    if (!kv) continue;
    const raw = kv[2].trim();
    meta[kv[1]] = raw.startsWith('[')
      ? raw.slice(1, -1).split(',').map((s) => s.trim()).filter(Boolean)
      : raw.replace(/^["']|["']$/g, '');
  }
  return { meta, body: text.slice(match[0].length) };
}

export function loadEntries() {
  const entries = [];
  for (const area of readdirSync(KNOWLEDGE)) {
    const dir = join(KNOWLEDGE, area);
    if (!statSync(dir).isDirectory()) continue;
    for (const name of readdirSync(dir)) {
      if (!name.endsWith('.md') || name.startsWith('_')) continue;
      const file = join(dir, name);
      const text = readFileSync(file, 'utf8');
      entries.push({ file, area, slug: basename(name, '.md'), text, ...parse(text) });
    }
  }
  return entries.sort((a, b) => a.area.localeCompare(b.area) || a.slug.localeCompare(b.slug));
}

export function validate(entries) {
  const errors = [];
  const slugs = new Set(entries.map((e) => `${e.area}/${e.slug}`));
  for (const e of entries) {
    const at = `${e.area}/${e.slug}.md`;
    const m = e.meta;
    if (!m) { errors.push(`${at}: no frontmatter`); continue; }
    if (!AREAS.includes(e.area)) errors.push(`${at}: folder must be one of ${AREAS.join(', ')}`);
    if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(e.slug)) errors.push(`${at}: file name must be kebab-case`);
    if (!m.title) errors.push(`${at}: title is required`);
    if (!TYPES.includes(m.type)) errors.push(`${at}: type must be one of ${TYPES.join(', ')}`);
    if (!Array.isArray(m.stack) || !m.stack.length || m.stack.some((s) => !STACKS.includes(s)))
      errors.push(`${at}: stack must be a list from ${STACKS.join(', ')}`);
    if (!m.author) errors.push(`${at}: author (GitHub login) is required`);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(m.updated ?? '')) errors.push(`${at}: updated must be YYYY-MM-DD`);
    if (m.status && !STATUSES.includes(m.status)) errors.push(`${at}: status must be active or deprecated`);
    for (const ref of [m.supersedes, m.replaced_by].filter(Boolean))
      if (!slugs.has(ref)) errors.push(`${at}: ${ref} does not exist (use <area>/<slug>)`);
    if (m.status === 'deprecated' && !m.replaced_by) errors.push(`${at}: deprecated entry needs replaced_by`);
    for (const h of REQUIRED_HEADINGS)
      if (!e.body.split('\n').includes(h)) errors.push(`${at}: missing section "${h}"`);
    if (e.text.split('\n').length > MAX_LINES) errors.push(`${at}: longer than ${MAX_LINES} lines, split it`);
  }
  return errors;
}

export function renderIndex(entries) {
  const rows = (list) =>
    list.map((e) => `| [${e.meta.title}](${e.area}/${e.slug}.md) | ${e.meta.type} | ${e.meta.stack.join(', ')} | ${e.meta.updated} |`);
  const active = entries.filter((e) => e.meta?.status !== 'deprecated');
  const deprecated = entries.filter((e) => e.meta?.status === 'deprecated');
  const out = [
    '# Индекс базы знаний',
    '',
    '<!-- Generated by scripts/knowledge.mjs index. Do not edit by hand. -->',
    '',
    `Статей: ${active.length}. Добавить свою: скилл \`frontend-contribute\`.`,
    '',
  ];
  for (const area of AREAS) {
    const list = active.filter((e) => e.area === area);
    if (!list.length) continue;
    out.push(`## ${area}`, '', '| Статья | Тип | Стек | Обновлено |', '|---|---|---|---|', ...rows(list), '');
  }
  if (deprecated.length)
    out.push('## Устарело', '', '| Статья | Тип | Стек | Обновлено |', '|---|---|---|---|', ...rows(deprecated), '');
  return out.join('\n');
}

// Search ranking: a term counts once per field, weighted title x3, tags x2, body x1.
// Terms are matched by crude stem prefix ("загрузка" finds "загрузки", "testing" finds "tests").
const WEIGHTS = { title: 3, tags: 2, body: 1 };
const ENDINGS = [
  'иями', 'ями', 'ами', 'ого', 'его', 'ому', 'ему', 'ыми', 'ими', 'ться', 'ing', 'ая', 'яя', 'ое', 'ее',
  'ые', 'ие', 'ой', 'ей', 'ий', 'ый', 'ом', 'ем', 'ам', 'ям', 'ах', 'ях', 'ов', 'ев', 'ия', 'ья', 'ть',
  'ed', 'es', 'ly', 'а', 'я', 'о', 'е', 'ы', 'и', 'у', 'ю', 'ь', 's',
];
export const MAX_RESULTS = 8;

export function stem(word) {
  const w = word.toLowerCase();
  for (const end of ENDINGS) if (w.endsWith(end) && w.length - end.length >= 4) return w.slice(0, -end.length);
  return w;
}

const tokenize = (text) => text.toLowerCase().split(/[^\p{L}\p{N}]+/u).filter(Boolean);

function fieldHas(fieldWords, term) {
  if (term.length < 4) return fieldWords.includes(term);
  const s = stem(term);
  return fieldWords.some((w) => w.startsWith(s));
}

/** Ranks entries for the query words; returns [{ e, score, matched }] best first, at most MAX_RESULTS. */
export function rank(entries, query, { stack, area } = {}) {
  const terms = [...new Set(query.flatMap(tokenize))];
  const pool = entries
    .filter((e) => e.meta && e.meta.status !== 'deprecated')
    .filter((e) => !area || e.area === area)
    .filter((e) => !stack || e.meta.stack.includes('all') || e.meta.stack.includes(stack));
  if (!terms.length) return pool.map((e) => ({ e, score: 0, matched: 0 }));
  const minMatched = terms.length >= 3 ? Math.ceil(terms.length / 2) : 1;
  return pool
    .map((e) => {
      const fields = { title: tokenize(e.meta.title ?? ''), tags: (e.meta.tags ?? []).flatMap(tokenize), body: tokenize(e.body) };
      let score = 0;
      let matched = 0;
      for (const t of terms) {
        let hit = false;
        for (const [name, weight] of Object.entries(WEIGHTS))
          if (fieldHas(fields[name], t)) { score += weight; hit = true; }
        if (hit) matched++;
      }
      return { e, score, matched };
    })
    .filter(({ matched }) => matched >= minMatched)
    .sort((a, b) => b.score - a.score || b.matched - a.matched || a.e.slug.localeCompare(b.e.slug))
    .slice(0, MAX_RESULTS);
}

function main(argv) {
  const [command, ...rest] = argv;
  const indexFile = join(KNOWLEDGE, 'INDEX.md');
  if (command === 'index') {
    writeFileSync(indexFile, renderIndex(loadEntries()));
    console.log(`wrote ${relative(process.cwd(), indexFile)}`);
    return 0;
  }
  if (command === 'check') {
    const entries = loadEntries();
    const errors = validate(entries);
    if (!existsSync(indexFile) || readFileSync(indexFile, 'utf8') !== renderIndex(entries))
      errors.push('knowledge/INDEX.md is out of date: run node plugins/frontend-pack/scripts/knowledge.mjs index');
    for (const e of errors) console.log(e);
    console.log(errors.length ? `${errors.length} problem(s)` : `${entries.length} entries ok`);
    return errors.length ? 1 : 0;
  }
  if (command === 'search') {
    const opts = {};
    const words = [];
    for (let i = 0; i < rest.length; i++) {
      if (rest[i] === '--stack' || rest[i] === '--area') opts[rest[i].slice(2)] = rest[++i];
      else words.push(rest[i]);
    }
    const found = rank(loadEntries(), words, opts);
    for (const { e, score } of found)
      console.log(`${e.file}\n    ${e.meta.title} [${e.meta.type}; ${e.meta.stack.join(', ')}; score ${score}]`);
    if (!found.length) console.log('nothing found');
    return 0;
  }
  console.log('usage: knowledge.mjs search <words...> [--stack s] [--area a] | index | check');
  return 1;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) process.exit(main(process.argv.slice(2)));
