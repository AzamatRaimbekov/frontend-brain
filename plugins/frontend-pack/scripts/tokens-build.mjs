#!/usr/bin/env node
// Generates registry/mbank/tokens.css from registry/mbank/shadcn-tokens.json (schema shadcn/tokens@1), the only
// token set of the design system: the standard shadcn/ui tokens, nothing custom. The json is a copy of the
// figma-pack owner (skills/ds-tokens/references/shadcn-tokens.json); design-engine sync-contracts keeps it equal.
// Usage:
//   node tokens-build.mjs                 write tokens.css
//   node tokens-build.mjs --check         exit 1 + a diff list when tokens.css is out of date
//   options: --tokens <shadcn-tokens.json> --out <tokens.css> --json
// Pure Node 18+, no dependencies.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const PLUGIN = join(dirname(fileURLToPath(import.meta.url)), '..');
export const DEFAULTS = {
  tokens: join(PLUGIN, 'registry', 'mbank', 'shadcn-tokens.json'),
  out: join(PLUGIN, 'registry', 'mbank', 'tokens.css'),
};
export const SCHEMA = 'shadcn/tokens@1';
// The shadcn init colour set, in the order shadcn writes it.
export const COLORS = [
  'background', 'foreground', 'card', 'card-foreground', 'popover', 'popover-foreground', 'primary', 'primary-foreground',
  'secondary', 'secondary-foreground', 'muted', 'muted-foreground', 'accent', 'accent-foreground', 'destructive',
  'border', 'input', 'ring', 'chart-1', 'chart-2', 'chart-3', 'chart-4', 'chart-5', 'sidebar', 'sidebar-foreground',
  'sidebar-primary', 'sidebar-primary-foreground', 'sidebar-accent', 'sidebar-accent-foreground', 'sidebar-border', 'sidebar-ring',
];
const RADII = ['sm', 'md', 'lg', 'xl', '2xl', '3xl', '4xl'];

/** Errors for a shadcn/tokens@1 object: exactly the shadcn colours (light + dark), radius, radius scale, fonts. */
export function validate(tokens) {
  const errors = [];
  if (tokens?.$schema !== SCHEMA) errors.push(`$schema must be "${SCHEMA}"`);
  if (typeof tokens?.radius !== 'string') errors.push('radius is required');
  for (const r of RADII) if (typeof tokens?.radiusScale?.[r] !== 'string') errors.push(`radiusScale.${r} is required`);
  if (typeof tokens?.font?.sans !== 'string') errors.push('font.sans is required');
  const names = Object.keys(tokens?.colors ?? {});
  for (const c of COLORS) {
    const v = tokens?.colors?.[c];
    if (!v) errors.push(`colors.${c} is missing`);
    else for (const mode of ['light', 'dark']) if (typeof v[mode] !== 'string' || !v[mode]) errors.push(`colors.${c}.${mode} is required`);
  }
  for (const n of names) if (!COLORS.includes(n)) errors.push(`colors.${n}: not a shadcn token (custom tokens are not allowed)`);
  return errors;
}

/** tokens.css text: :root light, .dark dark, @theme inline (--color-*, radius scale, fonts), base layer as shadcn init. */
export function render(tokens) {
  const errors = validate(tokens);
  if (errors.length) throw new Error(`shadcn-tokens.json is invalid:\n  ${errors.join('\n  ')}`);
  const fonts = Object.entries(tokens.font);
  const lines = [
    '/*',
    ' * Design tokens: the standard shadcn/ui set (Tailwind CSS v4), nothing custom.',
    ' * GENERATED by frontend-pack scripts/tokens-build.mjs from registry/mbank/shadcn-tokens.json.',
    ' * Do not edit by hand. A project changes only the VALUES of these names, never adds its own tokens.',
    ' *',
    ' * Usage (src/index.css or src/app/globals.css):',
    ' *   @import "tailwindcss";',
    ' *   @import "tw-animate-css";',
    ' *   @import "./styles/mbank-tokens.css";',
    ' * Theme: light on :root, dark on .dark (class on <html>).',
    ' */',
    '',
    '@custom-variant dark (&:is(.dark *));',
    '',
    '@theme inline {',
    ...fonts.map(([k, v]) => `  --font-${k}: ${v};`),
    ...COLORS.map((c) => `  --color-${c}: var(--${c});`),
    ...RADII.map((r) => `  --radius-${r}: ${tokens.radiusScale[r]};`),
    '}',
    '',
    ':root {',
    `  --radius: ${tokens.radius};`,
    ...COLORS.map((c) => `  --${c}: ${tokens.colors[c].light};`),
    '}',
    '',
    '.dark {',
    ...COLORS.map((c) => `  --${c}: ${tokens.colors[c].dark};`),
    '}',
    '',
    '@layer base {',
    '  * {',
    '    @apply border-border outline-ring/50;',
    '  }',
    '  body {',
    '    @apply bg-background text-foreground;',
    '  }',
    '  html {',
    '    @apply font-sans;',
    '  }',
    '}',
    '',
  ];
  return lines.join('\n');
}

const normSelector = (s) => s.trim().replace(/\s+/g, ' ');

/** CSS text -> Map(selector path -> Map(prop -> value)); nested rules use "a > b" keys, top-level at-rules sit in "(top)". */
export function parseCss(text) {
  const src = text.replace(/\/\*[\s\S]*?\*\//g, '');
  const out = new Map();
  const add = (key, stmt) => {
    const s = stmt.trim().replace(/\s+/g, ' ');
    if (!s) return;
    const at = s.startsWith('@');
    const i = at ? s.indexOf(' ') : s.indexOf(':');
    if (!out.has(key)) out.set(key, new Map());
    out.get(key).set(at ? s.slice(0, i) : s.slice(0, i).trim(), s.slice(i + 1).trim());
  };
  const walk = (from, to, key) => {
    let start = from;
    for (let i = from; i < to; i++) {
      if (src[i] === ';') { add(key, src.slice(start, i)); start = i + 1; }
      else if (src[i] === '{') {
        let depth = 1;
        let j = i + 1;
        for (; j < to && depth; j++) depth += src[j] === '{' ? 1 : src[j] === '}' ? -1 : 0;
        const sel = normSelector(src.slice(start, i));
        walk(i + 1, j - 1, key === '(top)' ? sel : `${key} > ${sel}`);
        i = j - 1;
        start = j;
      }
    }
    add(key, src.slice(start, to));
  };
  walk(0, src.length, '(top)');
  return out;
}

/** Semantic diff of two tokens.css texts: [{ selector, css, expected, actual }]. */
export function compareCss(expectedText, actualText) {
  const exp = parseCss(expectedText);
  const act = parseCss(actualText);
  const diffs = [];
  for (const sel of new Set([...exp.keys(), ...act.keys()])) {
    const e = exp.get(sel) ?? new Map();
    const a = act.get(sel) ?? new Map();
    for (const prop of new Set([...e.keys(), ...a.keys()])) {
      if (e.get(prop) !== a.get(prop)) diffs.push({ selector: sel, css: prop, expected: e.get(prop) ?? null, actual: a.get(prop) ?? null });
    }
  }
  return diffs;
}

export function parseArgs(argv) {
  const opts = { check: false, json: false, tokens: DEFAULTS.tokens, out: DEFAULTS.out };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--check') opts.check = true;
    else if (a === '--json') opts.json = true;
    else if (a === '--tokens' || a === '--out') opts[a.slice(2)] = resolve(argv[++i] ?? '');
    else throw new Error(`unknown argument ${a}`);
  }
  return opts;
}

/** { code, report } without touching process. */
export function run(argv) {
  const opts = parseArgs(argv);
  const css = render(JSON.parse(readFileSync(opts.tokens, 'utf8')));
  if (!opts.check) {
    writeFileSync(opts.out, css);
    return { code: 0, report: { written: opts.out } };
  }
  const actual = existsSync(opts.out) ? readFileSync(opts.out, 'utf8') : '';
  const diffs = actual === css ? [] : compareCss(css, actual);
  // Byte drift without a semantic diff (comments, spacing) still fails: the file must be the generated one.
  return { code: actual === css ? 0 : 1, report: { out: opts.out, upToDate: actual === css, diffs } };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    const argv = process.argv.slice(2);
    const { code, report } = run(argv);
    if (argv.includes('--json')) console.log(JSON.stringify(report, null, 2));
    else if (report.written) console.log(`written ${report.written}`);
    else if (report.upToDate) console.log('tokens.css is up to date');
    else {
      console.log('tokens.css is out of date: run node scripts/tokens-build.mjs');
      for (const d of report.diffs) console.log(`  ${d.selector} ${d.css}: expected ${d.expected ?? '(none)'}, got ${d.actual ?? '(none)'}`);
    }
    process.exit(code);
  } catch (error) {
    console.error(error.message);
    process.exit(2);
  }
}
