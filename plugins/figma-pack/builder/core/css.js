// shadcn tokens (canonical shape) -> globals.css for shadcn/ui on Tailwind CSS v4.
import { COLOR_TOKENS, SHADCN_TOKENS } from './tokens.js';

const block = (selector, t, theme, extra = []) =>
  [`${selector} {`, ...extra, ...COLOR_TOKENS.filter((k) => t.colors[k]).map((k) => `  --${k}: ${t.colors[k][theme]};`), '}'].join('\n');

/** t: { radius, radiusScale, font, colors: { name: { light, dark } } }; defaults to the canonical file. */
export function toShadcnCss(t = SHADCN_TOKENS, name = 'shadcn') {
  const scale = t.radiusScale || SHADCN_TOKENS.radiusScale;
  const font = t.font || SHADCN_TOKENS.font;
  const theme = [
    '@theme inline {',
    `  --font-sans: ${font.sans};`,
    `  --font-heading: ${font.heading};`,
    ...COLOR_TOKENS.map((k) => `  --color-${k}: var(--${k});`),
    ...Object.entries(scale).map(([k, v]) => `  --radius-${k}: ${v};`),
    '}',
  ].join('\n');
  return [
    `/* ${name}: shadcn/ui tokens generated by ds-builder, do not edit by hand */`,
    '@import "tailwindcss";',
    '@import "tw-animate-css";',
    '',
    '@custom-variant dark (&:is(.dark *));',
    '',
    block(':root', t, 'light', [`  --radius: ${t.radius || SHADCN_TOKENS.radius};`]),
    '',
    block('.dark', t, 'dark'),
    '',
    theme,
    '',
    '@layer base {',
    '  * { @apply border-border outline-ring/50; }',
    '  body { @apply bg-background text-foreground; }',
    '}',
    '',
  ].join('\n');
}
