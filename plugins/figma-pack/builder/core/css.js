// tokens.json -> globals.css for shadcn/ui on Tailwind CSS v4.
import { COLOR_TOKENS, radiusScale } from './tokens.js';

// t.custom: { 'mmarket-badge-bg-orange': { light: '#..', dark: '#..' } } -> extra vars + Tailwind colors.
const customLines = (t, theme) => Object.entries(t.custom || {}).filter(([, v]) => v[theme]).map(([k, v]) => `  --${k}: ${v[theme]};`);

const block = (selector, colors, extra = []) =>
  [`${selector} {`, ...extra, ...COLOR_TOKENS.filter((k) => colors[k]).map((k) => `  --${k}: ${colors[k]};`), '}'].join('\n');

export function toShadcnCss(t) {
  const r = radiusScale(t.radius);
  const theme = [
    '@theme inline {',
    `  --font-sans: "${t.font.sans}", ui-sans-serif, system-ui, sans-serif;`,
    `  --font-mono: "${t.font.mono}", ui-monospace, monospace;`,
    ...COLOR_TOKENS.map((k) => `  --color-${k}: var(--${k});`),
    ...Object.keys(t.custom || {}).map((k) => `  --color-${k}: var(--${k});`),
    `  --radius-sm: ${r.sm}px;`,
    `  --radius-md: ${r.md}px;`,
    `  --radius-lg: ${r.lg}px;`,
    `  --radius-xl: ${r.xl}px;`,
    '}',
  ].join('\n');
  return [
    `/* ${t.name}: generated by ds-builder from tokens.json, do not edit by hand */`,
    '@import "tailwindcss";',
    '@import "tw-animate-css";',
    '',
    '@custom-variant dark (&:is(.dark *));',
    '',
    block(':root', t.colors.light, [`  --radius: ${t.radius}px;`, ...customLines(t, 'light')]),
    '',
    block('.dark', t.colors.dark, customLines(t, 'dark')),
    '',
    theme,
    '',
    '@layer base {',
    '  * { @apply border-border outline-ring/50; }',
    '  body { @apply bg-background text-foreground; }',
    '}',
    '',
  ].join('\n');
}
