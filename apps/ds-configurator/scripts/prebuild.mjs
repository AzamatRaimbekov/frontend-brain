#!/usr/bin/env node
// Prebuild: writes src/generated/tokens.css (the app chrome theme) from src/data/shadcn-tokens.json,
// the app's copy of the canonical shadcn tokens. Warns when the copy drifted from the owner file
// (plugins/figma-pack/skills/ds-tokens/references/shadcn-tokens.json); the test suite fails on it.
// Usage: node scripts/prebuild.mjs   (runs before dev, build, test and typecheck)
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const APP = join(dirname(fileURLToPath(import.meta.url)), '..');
const COPY = join(APP, 'src', 'data', 'shadcn-tokens.json');
const OWNER = join(APP, '..', '..', 'plugins', 'figma-pack', 'skills', 'ds-tokens', 'references', 'shadcn-tokens.json');
const OUT = join(APP, 'src', 'generated');

const strip = ({ $copy: _c, ...rest }) => rest;

export function themeCss(tokens) {
  const names = Object.keys(tokens.colors);
  const block = (sel, lines) => `${sel} {\n${lines.map((l) => `  ${l}`).join('\n')}\n}`;
  return [
    '/* GENERATED by scripts/prebuild.mjs from src/data/shadcn-tokens.json (app chrome theme). Do not edit. */',
    '@custom-variant dark (&:is(.dark *));',
    '',
    block(':root', [`--radius: ${tokens.radius};`, ...names.map((n) => `--${n}: ${tokens.colors[n].light};`)]),
    '',
    block('.dark', names.map((n) => `--${n}: ${tokens.colors[n].dark};`)),
    '',
    block('@theme inline', [
      `--font-sans: ${tokens.font.sans};`,
      `--font-heading: ${tokens.font.heading};`,
      ...names.map((n) => `--color-${n}: var(--${n});`),
      ...Object.entries(tokens.radiusScale).map(([k, v]) => `--radius-${k}: ${v};`),
    ]),
    '',
  ].join('\n');
}

export function main() {
  const copy = JSON.parse(readFileSync(COPY, 'utf8'));
  if (existsSync(OWNER) && JSON.stringify(strip(copy)) !== JSON.stringify(JSON.parse(readFileSync(OWNER, 'utf8')))) {
    console.warn(`prebuild: WARNING src/data/shadcn-tokens.json differs from ${OWNER} - copy the owner file over it`);
  }
  mkdirSync(OUT, { recursive: true });
  writeFileSync(join(OUT, 'tokens.css'), themeCss(copy));
  console.log(`prebuild: ${Object.keys(copy.colors).length} shadcn colours -> src/generated/tokens.css`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
