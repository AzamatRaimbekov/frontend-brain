#!/usr/bin/env node
// Prebuild: copies the Mbank kit and tokens from plugins/frontend-pack into src/generated/ and
// builds src/generated/mbank-preset.json (CSS var -> value per mode and brand, plus the Figma
// variable name each var comes from). The app imports only src/generated/, never plugins/.
// Usage: node scripts/prebuild.mjs   (runs before dev, build and test)
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const APP = join(dirname(fileURLToPath(import.meta.url)), '..');
const REPO = join(APP, '..', '..');
const FRONTEND_PACK = process.env.FRONTEND_PACK_DIR ?? join(REPO, 'plugins', 'frontend-pack');
const MBANK = join(FRONTEND_PACK, 'registry', 'mbank');
const OUT = join(APP, 'src', 'generated');

// Kit components shown in the live preview (and their local imports).
export const KIT_COMPONENTS = [
  'alert', 'avatar', 'badge', 'button', 'card', 'checkbox', 'icons', 'input', 'label',
  'skeleton', 'spinner', 'switch', 'tabs', 'textarea', 'table',
];

const decls = (block) => (block?.items ?? []).filter((i) => i.prop);
const strip = (prop) => prop.replace(/^--/, '');

function varsOf(block) {
  const out = {};
  for (const d of decls(block)) {
    if (!d.prop.startsWith('--')) continue; // color-scheme
    out[strip(d.prop)] = d.value;
    for (const x of d.extra ?? []) out[strip(x.prop)] = x.value;
  }
  return out;
}

function figmaNames(block) {
  const out = {};
  for (const d of decls(block)) {
    if (d.src && !d.src.literal && (d.src.collection ?? 'theme') === 'theme') out[strip(d.prop)] = d.src.figma;
  }
  return out;
}

/** tokens.json + tokens.map.json -> the preset the configurator starts from. */
export async function buildPreset(tokens, map) {
  const { buildModel } = await import(pathToFileURL(join(FRONTEND_PACK, 'scripts', 'tokens-build.mjs')).href);
  const { blocks } = buildModel(tokens, map);
  const find = (selector) => blocks.find((b) => b.selector === selector);
  const brands = map.brand.modes;
  const preset = {
    $comment: 'GENERATED by apps/ds-configurator/scripts/prebuild.mjs from frontend-pack registry/mbank. Do not edit.',
    brands,
    light: varsOf(find(':root')),
    dark: varsOf(find('.dark')),
    brandLight: {},
    brandDark: {},
    // `--color-x: var(--x)` mappings are derived again on export; keep only real theme values and aliases.
    theme: Object.fromEntries(
      Object.entries({ ...varsOf(find('@theme inline')), ...varsOf(find('@theme')) })
        .filter(([k, v]) => !(k.startsWith('color-') && v === `var(--${k.slice(6)})`)),
    ),
    figma: figmaNames(find(':root')),
  };
  for (const b of brands) {
    preset.brandLight[b] = varsOf(find(`[data-brand="${b}"]`));
    preset.brandDark[b] = varsOf(find(`.dark[data-brand="${b}"], .dark [data-brand="${b}"]`));
  }
  // Brand vars come from 1.brand (light) and 2.theme brand/<mode>/* (dark); name them by the 1.brand variable.
  for (const t of map.brand.tokens) preset.figma[strip(t.css)] = `brand/${t.figma}`;
  return preset;
}

function copyKit() {
  const kit = join(OUT, 'kit');
  mkdirSync(join(kit, 'ui'), { recursive: true });
  mkdirSync(join(kit, 'lib'), { recursive: true });
  copyFileSync(join(MBANK, 'lib', 'utils.ts'), join(kit, 'lib', 'utils.ts'));
  for (const name of KIT_COMPONENTS) {
    const src = readFileSync(join(MBANK, 'components', `${name}.tsx`), 'utf8');
    const header = `// GENERATED copy of frontend-pack registry/mbank/components/${name}.tsx (prebuild). Do not edit.\n`;
    writeFileSync(join(kit, 'ui', `${name}.tsx`), header + src.replaceAll('@/shared/lib/utils', '../lib/utils'));
  }
}

export async function main() {
  if (!existsSync(MBANK)) throw new Error(`frontend-pack Mbank registry not found at ${MBANK} (set FRONTEND_PACK_DIR)`);
  rmSync(OUT, { recursive: true, force: true });
  mkdirSync(join(OUT, 'mbank'), { recursive: true });
  for (const f of ['tokens.json', 'tokens.map.json', 'tokens.css']) copyFileSync(join(MBANK, f), join(OUT, 'mbank', f));
  const read = (f) => JSON.parse(readFileSync(join(MBANK, f), 'utf8'));
  const preset = await buildPreset(read('tokens.json'), read('tokens.map.json'));
  writeFileSync(join(OUT, 'mbank-preset.json'), `${JSON.stringify(preset, null, 1)}\n`);
  copyKit();
  console.log(`prebuild: ${Object.keys(preset.light).length} light vars, ${preset.brands.length} brands, ${KIT_COMPONENTS.length} kit components -> src/generated/`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main().catch((e) => {
    console.error(`prebuild: ${e.message}`);
    process.exit(1);
  });
}
