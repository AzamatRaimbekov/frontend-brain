// use_figma script that writes the design system into the Figma collection `shadcn` (Light, Dark).
// Same plan (figma.json) the site serves per project, so both paths write identical variables.
import { SHADCN_TOKENS } from "../tokens"
import type { DesignSystem } from "../types"
import { buildFigmaPlan, FIGMA_COLLECTION, FIGMA_MODES } from "./figma-plan"
import { FIGMA_RUNTIME } from "./figma-runtime"

export const figmaPlanOf = (ds: DesignSystem) => buildFigmaPlan({ project: ds.name, name: ds.name, version: 1 }, ds.values, SHADCN_TOKENS)

export function buildFigmaScript(ds: DesignSystem) {
  const plan = figmaPlanOf(ds)
  return [
    `// ${ds.name} -> Figma variables. GENERATED by apps/ds-configurator. Run as the code of one use_figma call`,
    `// (needs a Full seat and edit access). Writes collection ${FIGMA_COLLECTION}, modes ${FIGMA_MODES.join(" / ")}:`,
    `// ${plan.variables.length} variables named as the CSS tokens (colours, radius, fonts), raw values. Deletes nothing.`,
    `const PLAN = ${JSON.stringify(plan)};`,
    FIGMA_RUNTIME,
  ].join("\n")
}
