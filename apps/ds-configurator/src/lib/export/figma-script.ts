// use_figma script that writes the design system as Figma variables (collection Brand, mode = brand).
// Values are the same resolved values the registry item and tokens.css carry.
import { hexToRgb, parseCssColor, resolveVar } from "../color"
import { toPx } from "../extra-tokens"
import { scopesFor } from "../figma-scopes"
import type { DesignSystem, ModeVars } from "../types"
import { FIGMA_RUNTIME } from "./figma-runtime"

export const THEME_COLLECTIONS = ["2.theme", "Mode"]

type Rgba = { r: number; g: number; b: number; a: number }
export type FigmaColor = { name: string; light: Rgba; dark: Rgba; scopes: string[]; figma: string | null; extra: boolean }
export type FigmaFloat = { figma: string; css: string; value: number; scopes: string[] }
export type FigmaPayload = {
  collection: string
  brand: string
  themeCollections: string[]
  colors: FigmaColor[]
  floats: FigmaFloat[]
  skipped: string[]
}

const round = (n: number) => Math.round(n * 10000) / 10000
const rgba = (hex: string): Rgba => {
  const { r, g, b, a } = hexToRgb(hex)
  return { r: round(r), g: round(g), b: round(b), a: round(a) }
}
const color = (key: string, vars: ModeVars) => {
  const v = vars[key] === undefined ? null : resolveVar(vars[key], vars)
  return v === null ? null : parseCssColor(v)
}
const PX = /^\d+(\.\d+)?(px|rem)$|^0$/

function floats(ds: DesignSystem): FigmaFloat[] {
  const out: FigmaFloat[] = []
  const radius = resolveVar(ds.light.radius ?? "", ds.light)
  if (radius && PX.test(radius)) out.push({ figma: "radius/default", css: "radius", value: toPx(radius), scopes: ["CORNER_RADIUS"] })
  for (const [k, v] of Object.entries(ds.theme)) {
    if (k.startsWith("radius-") && PX.test(v)) out.push({ figma: `radius/${k.slice(7)}`, css: k, value: toPx(v), scopes: ["CORNER_RADIUS"] })
  }
  for (const t of ds.state.extras) {
    if (t.kind === "color") continue
    const scopes = t.kind === "radius" ? ["CORNER_RADIUS"] : ["WIDTH_HEIGHT", "GAP"]
    out.push({ figma: `${t.kind}/${t.name}`, css: t.name, value: toPx(t.light), scopes })
  }
  return out
}

export function buildFigmaPayload(ds: DesignSystem): FigmaPayload {
  const dark = { ...ds.light, ...ds.dark } // .dark only overrides; the rest cascades from :root
  const extras = new Set(ds.state.extras.filter((t) => t.kind === "color").map((t) => t.name))
  const colors: FigmaColor[] = []
  const skipped: string[] = []
  for (const name of Object.keys(dark)) {
    const l = color(name, ds.light)
    const d = color(name, dark)
    if (!l && !d) continue
    if (!l || !d) {
      skipped.push(name)
      continue
    }
    colors.push({ name, light: rgba(l), dark: rgba(d), scopes: scopesFor(name), figma: ds.figma[name] ?? null, extra: extras.has(name) })
  }
  const brand = ds.state.source === "mbank" ? ds.state.brand : ds.name
  return { collection: "Brand", brand, themeCollections: THEME_COLLECTIONS, colors, floats: floats(ds), skipped }
}

export function buildFigmaScript(ds: DesignSystem, linkTheme = false) {
  const p = buildFigmaPayload(ds)
  return [
    `// ${ds.name} -> Figma variables. GENERATED by apps/ds-configurator. Run as the code of one use_figma call`,
    "// (needs a Full seat and edit access). Writes collection Brand, mode " + JSON.stringify(p.brand) + ":",
    `// ${p.colors.length} colours as color/light/<token> + color/dark/<token>, ${p.floats.length} numbers (radius/*, size/*).`,
    `// LINK_THEME = true also aliases the theme collection (${THEME_COLLECTIONS.join(" or ")}) light/dark modes to Brand.`,
    "// It rewires existing theme variables: run it on a branch or a copy of the library first.",
    p.skipped.length ? `// Skipped (colour in one mode only): ${p.skipped.join(", ")}` : "",
    `const LINK_THEME = ${linkTheme};`,
    `const DS = ${JSON.stringify({ ...p, skipped: undefined })};`,
    FIGMA_RUNTIME,
  ].filter(Boolean).join("\n")
}
