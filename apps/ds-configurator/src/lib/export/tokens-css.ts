// tokens.css for Tailwind v4 (+ shadcn/ui): :root (light), .dark, @theme inline, @layer base.
// Same layout as the shadcn CLI writes from a registry item, and as frontend-pack tokens.css.
import { parseCssColor, resolveVar } from "../color"
import type { DesignSystem, ModeVars } from "../types"

const rule = (selector: string, vars: ModeVars) =>
  `${selector} {\n${Object.entries(vars).map(([k, v]) => `  --${k}: ${v};`).join("\n")}\n}`

/** Names whose value is a colour in either mode: they get a --color-* utility mapping. */
export function colorTokenNames(ds: DesignSystem) {
  const dark = { ...ds.light, ...ds.dark }
  const isColor = (vars: ModeVars, key: string) => {
    const v = vars[key] === undefined ? null : resolveVar(vars[key], vars)
    return v !== null && parseCssColor(v) !== null
  }
  return Object.keys(dark).filter((k) => isColor(ds.light, k) || isColor(dark, k))
}

export function buildTokensCss(ds: DesignSystem) {
  const inline: ModeVars = {}
  for (const name of colorTokenNames(ds)) inline[`color-${name}`] = `var(--${name})`
  Object.assign(inline, ds.theme)
  return [
    "/*",
    ` * ${ds.name}: design tokens for Tailwind CSS v4 + shadcn/ui.`,
    " * GENERATED by apps/ds-configurator (fork of the shadcn/ui /create generator). Same values as",
    " * the registry:base item and the Figma Brand variables exported with it. Do not edit by hand.",
    " * Usage: @import \"tailwindcss\"; @import \"tw-animate-css\"; @import \"./tokens.css\";",
    " */",
    "",
    "@custom-variant dark (&:where(.dark, .dark *));",
    "",
    rule(":root", ds.light),
    "",
    rule(".dark", ds.dark),
    "",
    rule("@theme inline", inline),
    "",
    "@layer base {",
    "  * { @apply border-border outline-ring/50; }",
    "  body { @apply bg-background text-foreground; }",
    "}",
    "",
  ].join("\n")
}
